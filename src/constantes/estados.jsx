// Función para comparar localidades ignorando mayúsculas/minúsculas y acentos
export const normalizarTexto = (texto = "") => {
  return String(texto)
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
};